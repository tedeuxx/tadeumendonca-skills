#!/usr/bin/env python3
# purpose: regenerate this plugin's method carriers from one released tag of tedeuxx/mhw, deterministically, so a regeneration is reproducible from the tag and never touches a file the plugin owns
"""Regenerate the plugin's method carriers from a released tag of tedeuxx/mhw.

Usage:
    python3 scripts/mhw-regenerate.py --source <mhw git checkout> --tag <vX.Y.Z> [--target <plugin root>]

WHAT IT READS. Only the git objects of the named tag: `git archive <tag>^{commit} method`. It never
reads the source checkout's working tree, so an edited, dirty or differently checked-out mhw clone
cannot leak into the output. A name that does not resolve to a tag refuses the run (exit 2).

WHAT IT WRITES: the carrier map, and nothing else (mhw#191's intake, rows M1-M9 and S1-S2).

  method/skills/<n>/SKILL.md   -> skills/<n>/SKILL.md      M1 drop `name:`; M2 bare scalars; M3 tokens
  method/agents/<n>.md         -> agents/<n>.md            M2; M3
  method/commands/<n>.md       -> commands/<n>.md          M1 drop `name:` (no plugin command carries
                                                           it: the file name is the identifier); M2; M3
  method/scripts/<n>.py|.sh    -> scripts/<n>              S1, tests (`*.test.*`) excluded
  method/scripts/<dir>/**      -> scripts/<dir>/**         S1, every directory except `fixtures/`
  .claude-plugin/plugin.json   `skills` array and the skill/persona counts in `description`   (M4)
  .claude-plugin/marketplace.json  the skill count in the plugin description                  (M4)
  powers/                      regenerated by hooks/scripts/kiro-power-build.py               (M5)
  .mhw-regenerated             the watermark: tag, commit, and the list of generated paths    (M9)

  M3 renders `{{method-scripts}}` to `scripts`, the plugin-relative directory the plugin's carriers
  already call; a `{{method-scripts}}/<path>` naming no carried script stops the run, as mhw's own
  renderer does. M8: mhw text is never rewritten beyond these transforms.

WHAT IT NEVER TOUCHES (the owner's ruling on mhw#191, Q1: keep the plugin-only skills). A path outside
the carrier map is never written and never deleted. The one deletion it performs is of a path the
PREVIOUS watermark lists as generated and the new tag no longer carries. A map path that already
exists, was not generated by a previous run, and is either listed in PLUGIN_OWNED or met after the
first run, is a collision: the run stops before writing anything (exit 3).

Exit codes: 0 done, 2 bad source or tag, 3 collision with a plugin-owned path, 4 a transform refused.
"""

import argparse
import io
import json
import os
import re
import subprocess
import sys
import tarfile
from pathlib import Path

WATERMARK = ".mhw-regenerated"
TOKEN = "{{method-scripts}}"
# A sentence-ending period is not part of the path, so the last character of a target is not a dot.
TOKEN_REF_RE = re.compile(re.escape(TOKEN) + r"/((?:[A-Za-z0-9_.-]+/)*[A-Za-z0-9_.-]*[A-Za-z0-9_-])")
SCRIPT_RE = re.compile(r"[A-Za-z0-9_][A-Za-z0-9_.-]*\.(?:py|sh)")
NAME_RE = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
# Plugin-owned carriers the regeneration may never overwrite, even on the first run (mhw#191, Q1).
PLUGIN_OWNED = (
    "skills/backend/",
    "skills/cloud-infrastructure/",
    "skills/devops/",
    "skills/frontend/",
    "scripts/codex-",
)
# Source files deliberately not carried: mhw's own readme of the method directory.
IGNORED_SOURCES = {"method/README.md"}
# YAML plain scalars may not start with an indicator character.
PLAIN_FORBIDDEN_START = set("-?:,[]{}#&*!|>'\"%@`")
PLAIN_RESERVED = {"", "~", "null", "true", "false", "yes", "no", "on", "off", "y", "n"}
# Keys the plugin always writes quoted, whatever the value (every argument-hint in the plugin is).
ALWAYS_QUOTED = {"argument-hint"}


class RegenError(Exception):
    def __init__(self, code, message):
        super().__init__(message)
        self.code = code


def git(source, *args):
    proc = subprocess.run(["git", "-C", str(source), *args], capture_output=True)
    if proc.returncode != 0:
        raise RegenError(2, "git %s failed: %s" % (" ".join(args), proc.stderr.decode(errors="replace").strip()))
    return proc.stdout


def resolve_tag(source, tag):
    """The commit a TAG names. A branch or a bare SHA is refused: reproducibility is from a release."""
    if not re.fullmatch(r"v[0-9]+\.[0-9]+\.[0-9]+", tag):
        raise RegenError(2, "--tag must be a numeric SemVer release tag (vX.Y.Z), got %r" % tag)
    proc = subprocess.run(["git", "-C", str(source), "rev-parse", "--verify", "--quiet",
                           "refs/tags/%s^{commit}" % tag], capture_output=True)
    if proc.returncode != 0:
        raise RegenError(2, "tag %s does not exist in %s (fetch tags first)" % (tag, source))
    return proc.stdout.decode().strip()


def read_method(source, commit):
    """path -> (bytes, mode) for every blob under method/ at the commit."""
    data = git(source, "archive", "--format=tar", commit, "method")
    files = {}
    with tarfile.open(fileobj=io.BytesIO(data)) as tar:
        for member in tar.getmembers():
            if member.isfile():
                files[member.name] = (tar.extractfile(member).read(), member.mode & 0o777)
    if not any(p.startswith("method/skills/") for p in files):
        raise RegenError(2, "the tag carries no method/skills/: not an mhw release")
    return files


# ---------------------------------------------------------------------------------------------------
# Transforms

def plain_safe(value):
    """True when a value can be written as a YAML plain scalar and read back as the same string."""
    if value != value.strip() or value.lower() in PLAIN_RESERVED:
        return False
    if value[0] in PLAIN_FORBIDDEN_START or value.endswith(":"):
        return False
    # Any colon keeps the quotes, stricter than YAML on purpose: the plugin's description standard
    # (inventory-counts.test.sh, "NO UNQUOTED COLON") refuses an unquoted colon even where YAML allows one.
    if ":" in value or " #" in value or "\t" in value or "\n" in value:
        return False
    if re.fullmatch(r"[-+]?[0-9._]+(?:[eE][-+]?[0-9]+)?", value) or re.fullmatch(r"0[xo][0-9a-fA-F]+", value):
        return False
    return True


def transform_front_matter(text, where, drop_name):
    """M1 + M2 on a carrier's front matter; the body is returned untouched."""
    lines = text.split("\n")
    if not lines or lines[0] != "---":
        raise RegenError(4, "%s: no front matter" % where)
    try:
        end = lines.index("---", 1)
    except ValueError:
        raise RegenError(4, "%s: unterminated front matter" % where)
    out = ["---"]
    for line in lines[1:end]:
        m = re.fullmatch(r"([a-z][a-z-]*):(.*)", line)
        if m and m.group(1) == "name" and drop_name:
            continue                                                      # M1
        if m and m.group(2).strip().startswith('"'):
            raw = m.group(2).strip()
            try:
                value = json.loads(raw)
            except ValueError:
                raise RegenError(4, "%s: invalid quoted value for %s" % (where, m.group(1)))
            if not isinstance(value, str):
                raise RegenError(4, "%s: %s is not a string" % (where, m.group(1)))
            bare = plain_safe(value) and m.group(1) not in ALWAYS_QUOTED
            out.append("%s: %s" % (m.group(1), value if bare else raw))      # M2
            continue
        out.append(line)
    return "\n".join(out + lines[end:])


def render_tokens(text, where, scripts):
    """M3: {{method-scripts}} -> scripts; every named target must be a carried script or document."""
    for target in TOKEN_REF_RE.findall(text):
        if "scripts/" + target not in scripts:
            raise RegenError(4, "%s: %s/%s names no file carried into scripts/" % (where, TOKEN, target))
    return text.replace(TOKEN, "scripts")


def build_map(files):
    """target path -> (bytes, mode), from the source files. Unknown source layouts refuse the run."""
    scripts, carriers, unmapped = {}, {}, []
    for path, (data, mode) in sorted(files.items()):
        if path in IGNORED_SOURCES:
            continue
        parts = path.split("/")
        if parts[1] == "scripts":
            rest = parts[2:]
            if len(rest) == 1:
                if SCRIPT_RE.fullmatch(rest[0]) and ".test." not in rest[0]:
                    scripts["scripts/" + rest[0]] = (data, mode)               # S1
                elif not SCRIPT_RE.fullmatch(rest[0]):
                    unmapped.append(path)
            elif rest[0] != "fixtures":
                scripts["scripts/" + "/".join(rest)] = (data, mode)            # S1, contract directories
            continue
        if parts[1] == "skills" and len(parts) == 4 and parts[3] == "SKILL.md" and NAME_RE.fullmatch(parts[2]):
            carriers[path] = ("skills/%s/SKILL.md" % parts[2], True, data, mode)
        elif parts[1] in ("agents", "commands") and len(parts) == 3 and parts[2].endswith(".md") \
                and NAME_RE.fullmatch(parts[2][:-3]):
            carriers[path] = ("%s/%s" % (parts[1], parts[2]), parts[1] == "commands", data, mode)
        else:
            unmapped.append(path)
    if unmapped:
        raise RegenError(4, "source files outside the carrier map (extend the map deliberately): " + ", ".join(unmapped))
    out = dict(scripts)
    for path, (target, drop_name, data, mode) in carriers.items():
        text = data.decode("utf-8")
        text = transform_front_matter(text, path, drop_name)
        text = render_tokens(text, path, scripts)
        out[target] = (text.encode("utf-8"), mode)
    return out


# ---------------------------------------------------------------------------------------------------
# Writing

def read_watermark(target):
    path = target / WATERMARK
    if not path.exists():
        return None
    generated = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("  "):
            generated.append(line.strip())
    return set(generated)


def check_collisions(target, new_map, previous):
    collisions = []
    for rel in sorted(new_map):
        if not (target / rel).exists():
            continue
        if previous is not None and rel in previous:
            continue
        if previous is not None or rel.startswith(PLUGIN_OWNED):
            collisions.append(rel)
    if collisions:
        raise RegenError(3, "would overwrite plugin-owned path(s) not generated by a previous run: " + ", ".join(collisions))


def write_file(path, data, mode):
    changed = not path.exists() or path.read_bytes() != data
    if changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    want = 0o755 if mode & 0o100 else 0o644
    if (path.stat().st_mode & 0o777) != want:
        os.chmod(path, want)
        changed = True
    return changed


def update_manifests(target):
    """M4: the skills array lists every skill directory present; the published counts follow it."""
    present = sorted(p.parent.name for p in (target / "skills").glob("*/SKILL.md"))
    agents = sorted(p.stem for p in (target / "agents").glob("*.md"))
    manifest_path = target / ".claude-plugin" / "plugin.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    kept = [s for s in manifest.get("skills", []) if s.rsplit("/", 1)[-1] in present]
    known = {s.rsplit("/", 1)[-1] for s in kept}
    manifest["skills"] = kept + ["./skills/%s" % n for n in present if n not in known]
    manifest["description"] = re.sub(r"\b\d+ generic skills\b", "%d generic skills" % len(present),
                                     manifest["description"])
    manifest["description"] = re.sub(r"\b\d+ subagent personas\b", "%d subagent personas" % len(agents),
                                     manifest["description"])
    changed = write_file(manifest_path, (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode(), 0o644)
    market_path = target / ".claude-plugin" / "marketplace.json"
    market = market_path.read_text(encoding="utf-8")
    new_market = re.sub(r"\b\d+ generic skills\b", "%d generic skills" % len(present), market)
    if new_market != market:
        market_path.write_text(new_market, encoding="utf-8")
        changed = True
    return changed


def regenerate_powers(target):
    """M5: the Kiro export is the generator's output and nothing else."""
    proc = subprocess.run([sys.executable, str(target / "hooks" / "scripts" / "kiro-power-build.py")],
                          cwd=str(target), capture_output=True)
    if proc.returncode != 0:
        raise RegenError(4, "kiro-power-build.py failed: %s" % proc.stderr.decode(errors="replace").strip())


def watermark_text(tag, commit, generated):
    lines = ["# Written by scripts/mhw-regenerate.py. Do not edit: the next regeneration rewrites it.",
             "tag: %s" % tag, "commit: %s" % commit, "generated:"]
    lines += ["  " + p for p in sorted(generated)]
    return "\n".join(lines) + "\n"


def regenerate(source, tag, target, powers=True):
    target = Path(target).resolve()
    commit = resolve_tag(source, tag)
    new_map = build_map(read_method(source, commit))
    previous = read_watermark(target)
    check_collisions(target, new_map, previous)
    report = {"written": [], "deleted": [], "unchanged": 0}
    for rel, (data, mode) in sorted(new_map.items()):
        if write_file(target / rel, data, mode):
            report["written"].append(rel)
        else:
            report["unchanged"] += 1
    for rel in sorted((previous or set()) - set(new_map)):
        path = target / rel
        if path.exists():
            path.unlink()
            report["deleted"].append(rel)
            parent = path.parent
            while parent != target and not any(parent.iterdir()):
                parent.rmdir()
                parent = parent.parent
    if update_manifests(target):
        report["written"].append(".claude-plugin/")
    if powers:
        regenerate_powers(target)
    if write_file(target / WATERMARK, watermark_text(tag, commit, new_map).encode(), 0o644):
        report["written"].append(WATERMARK)
    return commit, report


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--source", required=True, help="an mhw git checkout holding the tag")
    parser.add_argument("--tag", required=True, help="the mhw release tag, vX.Y.Z")
    parser.add_argument("--target", default=str(Path(__file__).resolve().parents[1]),
                        help="the plugin root (default: this script's repository)")
    args = parser.parse_args(argv)
    try:
        commit, report = regenerate(args.source, args.tag, args.target)
    except RegenError as error:
        print("mhw-regenerate: %s" % error, file=sys.stderr)
        return error.code
    print("mhw-regenerate: %s (%s): %d written, %d deleted, %d unchanged"
          % (args.tag, commit, len(report["written"]), len(report["deleted"]), report["unchanged"]))
    for rel in report["written"]:
        print("  written  " + rel)
    for rel in report["deleted"]:
        print("  deleted  " + rel)
    return 0


if __name__ == "__main__":
    sys.exit(main())
